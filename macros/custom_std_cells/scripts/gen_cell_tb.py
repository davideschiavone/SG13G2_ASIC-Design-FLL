def fill(template: str, **tokens: str) -> str:
    """Substitute @TOKEN@ placeholders. Used instead of str.format because these
    templates are full of literal braces (make, awk, SystemVerilog concatenations)."""
    out = template
    for key, val in tokens.items():
        out = out.replace(f"@{key.upper()}@", val)
    left = re.findall(r"@[A-Z_]+@", out)
    if left:
        raise GenError(f"unsubstituted template tokens: {sorted(set(left))}")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Generate exhaustive Verilator/Icarus testbenches for a std-cell netlist.",
        epilog="All library paths are explicit arguments so the tool is not tied to any one PDK.",
    )
    ap.add_argument("netlist", type=Path, help="structural Verilog netlist (e.g. aion_cells.v)")
    ap.add_argument(
        "--lib",
        type=Path,
        required=True,
        metavar="FILE",
        help="Liberty file whose 'function' attributes are the gold oracle (required)",
    )
    ap.add_argument(
        "--cell-verilog",
        type=Path,
        action="append",
        default=[],
        metavar="FILE",
        help="simulation model for the standard cells, baked into the generated Makefile; "
        "repeat for several files (required unless --no-makefile)",
    )
    ap.add_argument(
        "-o",
        "--outdir",
        type=Path,
        default=None,
        metavar="DIR",
        help="output directory (default: <netlist dir>/tb)",
    )
    ap.add_argument(
        "--max-inputs",
        type=int,
        default=16,
        metavar="N",
        help="refuse modules with more inputs than this (default: 16)",
    )
    ap.add_argument(
        "--no-strip-specify",
        dest="strip_specify",
        action="store_false",
        help="compile the cell models as-is instead of stripping their 'specify' blocks",
    )
    ap.add_argument(
        "--no-makefile",
        action="store_true",
        help="emit only the testbenches and gold_functions.md (no Makefile, no README.md)",
    )
    args = ap.parse_args(argv)

    netlist: Path = args.netlist
    if not netlist.is_file():
        raise GenError(f"netlist not found: {netlist}")

    lib_path: Path = args.lib
    if not lib_path.is_file():
        raise GenError(f"Liberty file not found: {lib_path}")

    cell_v: list[Path] = list(args.cell_verilog)
    if not args.no_makefile and not cell_v:
        raise GenError(
            "--cell-verilog is required to generate the Makefile: the testbenches instantiate "
            "the standard cells, so the simulators need their models. Pass it once per file, "
            "or use --no-makefile."
        )
    for f in cell_v:
        if not f.is_file():
            raise GenError(f"cell Verilog model not found: {f}")

    outdir: Path = args.outdir or netlist.parent / "tb"
    script_name = f"scripts/{Path(__file__).name}"

    modules = parse_netlist(netlist)
    used_cells = {inst.cell for m in modules for inst in m.instances}
    lib = parse_liberty(lib_path, used_cells)

    models: list[GoldModel] = []
    tables: dict[str, dict[str, list[int]]] = {}
    for mod in modules:
        if len(mod.inputs) > args.max_inputs:
            raise GenError(
                f"module '{mod.name}' has {len(mod.inputs)} inputs, above --max-inputs "
                f"{args.max_inputs}; exhaustive simulation would need {2 ** len(mod.inputs)} vectors"
            )
        gm = build_gold(mod, lib)
        models.append(gm)
        tables[mod.name] = gold_truth_table(gm)

    outdir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for gm in models:
        path = outdir / f"tb_{gm.module.name}.sv"
        path.write_text(emit_tb(gm, script_name, netlist.name, lib_path.name))
        written.append(path)

    report = outdir / "gold_functions.md"
    report.write_text(emit_report(models, tables, script_name, netlist.name, lib_path.name))
    written.append(report)

    if not args.no_makefile:
        netlist_rel = os.path.relpath(netlist.resolve(), outdir.resolve())
        cell_abs = [str(f.resolve()) for f in cell_v]
        mk = outdir / "Makefile"
        mk.write_text(
            fill(
                MAKEFILE_TEMPLATE,
                script=script_name,
                netlist=netlist.name,
                netlistrel=netlist_rel,
                cellsrc=" ".join(cell_abs),
                stripblock=STRIP_BLOCK if args.strip_specify else NO_STRIP_BLOCK,
                tblist=" \\\n".join(f"\ttb_{gm.module.name}" for gm in models),
            )
        )
        written.append(mk)

        gencmd = " \\\n    ".join(
            [f"{Path(__file__).name} {netlist}", f"--lib {lib_path}"]
            + [f"--cell-verilog {f}" for f in cell_v]
            + ([] if args.strip_specify else ["--no-strip-specify"])
        )
        example = models[0]
        rd = outdir / "README.md"
        rd.write_text(
            fill(
                README_TEMPLATE,
                script=script_name,
                scriptbase=Path(__file__).name,
                netlist=netlist.name,
                netlistrel=netlist_rel,
                lib=lib_path.name,
                cellsrclist=" ".join(cell_abs),
                gencmd=gencmd,
                ntb=str(len(models)),
                nvec=str(sum(2 ** len(gm.module.inputs) for gm in models)),
                catdut=", ".join(reversed(example.module.outputs)),
                catgold=", ".join(example.gold_name(o) for o in reversed(example.module.outputs)),
                examplemod=example.module.name,
                examplevec=str(2 ** len(example.module.inputs)),
                examplegold="\n".join(
                    f"assign {example.gold_name(ga.net)} = {gold_sv_expr(example, ga)};"
                    f"  // {ga.inst.name} {ga.inst.cell}: {ga.out_pin} = {ga.lib_func}"
                    for ga in example.assigns
                ),
                modtable="\n".join(
                    f"| `tb_{gm.module.name}.sv` | {len(gm.module.inputs)} | "
                    f"{len(gm.module.outputs)} | {2 ** len(gm.module.inputs)} |"
                    for gm in models
                ),
            )
        )
        written.append(rd)

    print(f"Liberty oracle : {lib_path}")
    for f in cell_v:
        print(f"Cell models    : {f}")
    print(f"Netlist        : {netlist}  ({len(modules)} modules, {len(used_cells)} distinct cells)")
    print(f"Output         : {outdir}")
    for gm in models:
        print(
            f"  tb_{gm.module.name:<32} {len(gm.module.inputs)} in, "
            f"{len(gm.module.outputs)} out, {2 ** len(gm.module.inputs)} vectors"
        )
    print(f"Wrote {len(written)} files.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except GenError as exc:
        print(f"error: {exc}", file=sys.stderr)
        sys.exit(1)
