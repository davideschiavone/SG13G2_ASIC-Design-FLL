class GenError(Exception):
    """Fatal, user-facing generator error."""


# --------------------------------------------------------------------------------------
# Verilog netlist parsing
# --------------------------------------------------------------------------------------


@dataclass
class Instance:
    cell: str
    name: str
    conns: dict[str, str]  # formal pin -> actual net


@dataclass
class Module:
    name: str
    inputs: list[str] = field(default_factory=list)
    outputs: list[str] = field(default_factory=list)
    wires: list[str] = field(default_factory=list)
    instances: list[Instance] = field(default_factory=list)


_RE_MODULE = re.compile(r"\bmodule\s+(\w+)\s*\((.*?)\)\s*;", re.S)
_RE_ENDMODULE = re.compile(r"\bendmodule\b")
_RE_DECL = re.compile(r"\b(input|output|wire)\s+(\w+)\s*;")
_RE_INST = re.compile(r"\b(\w+)\s+(\w+)\s*\((.*?)\)\s*;", re.S)
_RE_CONN = re.compile(r"\.(\w+)\s*\(\s*(\w+)\s*\)")


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return text


def parse_netlist(path: Path) -> list[Module]:
    """Parse a flat structural Verilog netlist into Module objects.

    Only the subset emitted by aion_opt is supported: scalar ``input``/``output``/``wire``
    declarations and named-port cell instances.  Anything else is rejected loudly.
    """
    src = strip_comments(path.read_text())

    modules: list[Module] = []
    pos = 0
    while True:
        m = _RE_MODULE.search(src, pos)
        if not m:
            break
        end = _RE_ENDMODULE.search(src, m.end())
        if not end:
            raise GenError(f"{path}: module '{m.group(1)}' has no matching 'endmodule'")
        body = src[m.end() : end.start()]
        pos = end.end()

        mod = Module(name=m.group(1))
        port_order = [p.strip() for p in m.group(2).split(",") if p.strip()]

        seen: set[str] = set()
        for kind, sig in _RE_DECL.findall(body):
            if kind == "input":
                if sig not in seen:
                    mod.inputs.append(sig)
            elif kind == "output":
                if sig not in seen:
                    mod.outputs.append(sig)
            elif sig not in mod.inputs and sig not in mod.outputs:
                if sig not in seen:
                    mod.wires.append(sig)
            seen.add(sig)

        declared = set(mod.inputs) | set(mod.outputs)
        missing = [p for p in port_order if p not in declared]
        if missing:
            raise GenError(
                f"{path}: module '{mod.name}' ports {missing} have no input/output declaration"
            )

        # Keep the header port order for the ports; it is what the instantiation uses.
        mod.inputs = [p for p in port_order if p in set(mod.inputs)]
        mod.outputs = [p for p in port_order if p in set(mod.outputs)]

        # Instances: search the body with declarations removed so 'input x;' can't match.
        inst_body = _RE_DECL.sub(" ", body)
        for cell, iname, conn_txt in _RE_INST.findall(inst_body):
            conns = dict(_RE_CONN.findall(conn_txt))
            if not conns:
                raise GenError(
                    f"{path}: module '{mod.name}': instance '{iname}' of '{cell}' uses "
                    "positional or unsupported port connections; only .pin(net) is supported"
                )
            leftover = _RE_CONN.sub(" ", conn_txt).replace(",", " ").strip()
            if leftover:
                raise GenError(
                    f"{path}: module '{mod.name}': instance '{iname}' has unparsable "
                    f"connection text: {leftover!r}"
                )
            mod.instances.append(Instance(cell=cell, name=iname, conns=conns))

        if not mod.instances:
            raise GenError(f"{path}: module '{mod.name}' contains no cell instances")

        modules.append(mod)

    if not modules:
        raise GenError(f"{path}: no modules found")
    return modules


# --------------------------------------------------------------------------------------
# Liberty parsing
# --------------------------------------------------------------------------------------


@dataclass
class LibCell:
    name: str
    directions: dict[str, str] = field(default_factory=dict)
    functions: dict[str, str] = field(default_factory=dict)

    @property
    def inputs(self) -> list[str]:
        return [p for p, d in self.directions.items() if d == "input"]

    @property
    def outputs(self) -> list[str]:
        return [p for p, d in self.directions.items() if d == "output"]


_RE_CELL_OPEN = re.compile(r"^\s*cell\s*\(\s*([\w\\\[\]]+)\s*\)\s*\{")
_RE_PIN_OPEN = re.compile(r"^\s*pin\s*\(\s*([\w\\\[\]]+)\s*\)\s*\{")
_RE_DIRECTION = re.compile(r'^\s*direction\s*:\s*"?(\w+)"?\s*;')
_RE_FUNCTION = re.compile(r'^\s*function\s*:\s*"(.*)"\s*;')


def parse_liberty(path: Path, wanted: set[str]) -> dict[str, LibCell]:
    """Extract pin directions and output functions for the requested cells.

    A simple brace-depth scanner is enough: we only need ``cell(){ pin(){ ... } }`` and
    the leaf attributes ``direction`` and ``function``.
    """
    cells: dict[str, LibCell] = {}
    cur: LibCell | None = None
    cur_depth = 0
    pin: str | None = None
    pin_depth = 0
    depth = 0

    with path.open() as fh:
        for line in fh:
            m = _RE_CELL_OPEN.match(line)
            if m:
                depth += line.count("{") - line.count("}")
                name = m.group(1)
                if name in wanted:
                    cur = LibCell(name=name)
                    cells[name] = cur
                    cur_depth = depth
                    pin = None
                continue

            if cur is not None:
                m = _RE_PIN_OPEN.match(line)
                if m:
                    depth += line.count("{") - line.count("}")
                    pin = m.group(1)
                    pin_depth = depth
                    continue
                if pin is not None:
                    m = _RE_DIRECTION.match(line)
                    if m:
                        cur.directions[pin] = m.group(1)
                    m = _RE_FUNCTION.match(line)
                    if m:
                        cur.functions[pin] = m.group(1)

            depth += line.count("{") - line.count("}")
            if pin is not None and depth < pin_depth:
                pin = None
            if cur is not None and depth < cur_depth:
                cur = None
                pin = None

    missing = sorted(wanted - set(cells))
    if missing:
        raise GenError(
            "the netlist instantiates module(s) that are not standard cells of the given "
            f"library: {', '.join(missing)}\n"
            f"  no 'cell (<name>)' entry for them in {path}\n"
            "  Every instance must be a leaf standard cell, so its function can be taken from "
            "Liberty; sub-modules defined in the netlist itself, cells from another library, or "
            "typo'd cell names cannot be given a gold model. Fix the netlist, or point --lib at "
            "the library that defines these cells."
        )
    return cells


# --------------------------------------------------------------------------------------
# Liberty boolean expression parser
#
# Grammar (loosest binding first):
#   or   := xor  (('+' | '|') xor)*
#   xor  := and  ('^' and)*
#   and  := not  (('*' | '&')? not)*          -- juxtaposition means AND
#   not  := '!' not | atom "'"*
#   atom := '(' or ')' | identifier | '0' | '1'
# --------------------------------------------------------------------------------------


@dataclass
class Node:
    op: str  # 'var' | 'const' | 'not' | 'and' | 'or' | 'xor'
    value: str | int | None = None
    kids: list["Node"] = field(default_factory=list)


_RE_TOKEN = re.compile(r"\s*([A-Za-z_]\w*|\d+|[()+|^*&!'])")


def _tokenize(expr: str) -> list[str]:
    toks: list[str] = []
    pos = 0
    while pos < len(expr):
        m = _RE_TOKEN.match(expr, pos)
        if not m:
            if expr[pos:].strip() == "":
                break
            raise GenError(f"cannot tokenize Liberty expression {expr!r} at offset {pos}")
        toks.append(m.group(1))
        pos = m.end()
    return toks


class _LibExprParser:
    def __init__(self, expr: str):
        self.expr = expr
        self.toks = _tokenize(expr)
        self.i = 0

    def peek(self) -> str | None:
        return self.toks[self.i] if self.i < len(self.toks) else None

    def take(self) -> str:
        tok = self.toks[self.i]
        self.i += 1
        return tok

    def parse(self) -> Node:
        node = self.p_or()
        if self.peek() is not None:
            raise GenError(f"trailing tokens in Liberty expression {self.expr!r}: {self.toks[self.i:]}")
        return node

    def p_or(self) -> Node:
        kids = [self.p_xor()]
        while self.peek() in ("+", "|"):
            self.take()
            kids.append(self.p_xor())
        return kids[0] if len(kids) == 1 else Node("or", kids=kids)

    def p_xor(self) -> Node:
        kids = [self.p_and()]
        while self.peek() == "^":
            self.take()
            kids.append(self.p_and())
        return kids[0] if len(kids) == 1 else Node("xor", kids=kids)

    def p_and(self) -> Node:
        kids = [self.p_not()]
        while True:
            tok = self.peek()
            if tok in ("*", "&"):
                self.take()
                kids.append(self.p_not())
            elif tok is not None and (tok == "(" or tok == "!" or tok[0].isalnum() or tok[0] == "_"):
                # juxtaposition, e.g. "A B" or "A!B"
                kids.append(self.p_not())
            else:
                break
        return kids[0] if len(kids) == 1 else Node("and", kids=kids)

    def p_not(self) -> Node:
        if self.peek() == "!":
            self.take()
            return Node("not", kids=[self.p_not()])
        node = self.p_atom()
        while self.peek() == "'":
            self.take()
            node = Node("not", kids=[node])
        return node

    def p_atom(self) -> Node:
        tok = self.peek()
        if tok is None:
            raise GenError(f"unexpected end of Liberty expression {self.expr!r}")
        if tok == "(":
            self.take()
            node = self.p_or()
            if self.peek() != ")":
                raise GenError(f"missing ')' in Liberty expression {self.expr!r}")
            self.take()
            return node
        self.take()
        if tok.isdigit():
            if tok not in ("0", "1"):
                raise GenError(f"unsupported constant {tok!r} in {self.expr!r}")
            return Node("const", value=int(tok))
        if tok[0].isalpha() or tok[0] == "_":
            return Node("var", value=tok)
        raise GenError(f"unexpected token {tok!r} in Liberty expression {self.expr!r}")


def parse_lib_expr(expr: str) -> Node:
    return _LibExprParser(expr).parse()


def render_sv(node: Node, subst: dict[str, str]) -> str:
    """Render an AST as a fully parenthesised SystemVerilog bit expression."""
    if node.op == "const":
        return "1'b1" if node.value else "1'b0"
    if node.op == "var":
        name = str(node.value)
        if name not in subst:
            raise GenError(f"Liberty function references unconnected pin '{name}'")
        return subst[name]
    if node.op == "not":
        return f"~{render_sv(node.kids[0], subst)}"
    sym = {"and": " & ", "or": " | ", "xor": " ^ "}[node.op]
    return "(" + sym.join(render_sv(k, subst) for k in node.kids) + ")"


def eval_node(node: Node, env: dict[str, int]) -> int:
    if node.op == "const":
        return int(node.value or 0)
    if node.op == "var":
        return env[str(node.value)]
    if node.op == "not":
        return 1 - eval_node(node.kids[0], env)
    vals = [eval_node(k, env) for k in node.kids]
    if node.op == "and":
        return int(all(vals))
    if node.op == "or":
        return int(any(vals))
    if node.op == "xor":
        out = 0
        for v in vals:
            out ^= v
        return out
    raise GenError(f"unknown node op {node.op!r}")


# --------------------------------------------------------------------------------------
# Gold model construction
# --------------------------------------------------------------------------------------


@dataclass
class GoldAssign:
    net: str  # module net driven
    inst: Instance
    out_pin: str
    lib_func: str
    ast: Node
    pin_to_net: dict[str, str]  # formal pin -> module net (inputs of this cell only)


@dataclass
class GoldModel:
    module: Module
    assigns: list[GoldAssign]
    order: list[str]  # topological order of driven nets

    def gold_name(self, net: str) -> str:
        return net if net in self.module.inputs else f"g_{net}"


# Identifiers the testbench template declares itself; a module port using one of these
# would silently shadow it.
TB_RESERVED = {"vec", "dut_o", "gold_o", "diff", "correct", "errors", "u_dut", "v", "NI", "NO"}


def build_gold(mod: Module, lib: dict[str, LibCell]) -> GoldModel:
    inputs = set(mod.inputs)
    driver: dict[str, GoldAssign] = {}

    clashes = sorted(p for p in mod.inputs + mod.outputs if p in TB_RESERVED)
    if clashes:
        raise GenError(
            f"module '{mod.name}': port(s) {clashes} collide with identifiers the testbench "
            "template declares; rename them in the netlist"
        )
    shadowed = sorted(p for p in mod.inputs if p.startswith("g_"))
    if shadowed:
        raise GenError(
            f"module '{mod.name}': input(s) {shadowed} start with 'g_', which is the prefix "
            "used for gold-model signals"
        )

    for inst in mod.instances:
        cell = lib[inst.cell]
        if not cell.functions:
            raise GenError(
                f"module '{mod.name}': cell '{inst.cell}' has no Liberty output function "
                "(sequential or black-box cells are not supported)"
            )
        for pin, net in inst.conns.items():
            if pin not in cell.directions:
                raise GenError(
                    f"module '{mod.name}': instance '{inst.name}' connects pin '{pin}', "
                    f"which is not a pin of '{inst.cell}'"
                )
        for out_pin, func in cell.functions.items():
            if out_pin not in inst.conns:
                raise GenError(
                    f"module '{mod.name}': instance '{inst.name}' leaves output pin "
                    f"'{out_pin}' of '{inst.cell}' unconnected"
                )
            net = inst.conns[out_pin]
            if net in inputs:
                raise GenError(
                    f"module '{mod.name}': instance '{inst.name}' drives primary input '{net}'"
                )
            if net in driver:
                raise GenError(
                    f"module '{mod.name}': net '{net}' is driven by both "
                    f"'{driver[net].inst.name}' and '{inst.name}'"
                )
            ast = parse_lib_expr(func)
            pin_to_net = {p: n for p, n in inst.conns.items() if cell.directions[p] == "input"}
            driver[net] = GoldAssign(
                net=net, inst=inst, out_pin=out_pin, lib_func=func, ast=ast, pin_to_net=pin_to_net
            )

    for out in mod.outputs:
        if out not in driver:
            raise GenError(f"module '{mod.name}': output '{out}' is undriven")

    # Every read net must be a primary input or driven by some instance.
    for ga in driver.values():
        for pin, net in ga.pin_to_net.items():
            if net not in inputs and net not in driver:
                raise GenError(
                    f"module '{mod.name}': instance '{ga.inst.name}' pin '{pin}' reads "
                    f"undriven net '{net}'"
                )

    order = _topo_order(mod, driver, inputs)
    return GoldModel(module=mod, assigns=[driver[n] for n in order], order=order)


def _topo_order(mod: Module, driver: dict[str, GoldAssign], inputs: set[str]) -> list[str]:
    """Depth-first topological sort of the driven nets; raises on a combinational loop."""
    order: list[str] = []
    state: dict[str, int] = {}  # 0 = visiting, 1 = done
    stack: list[str] = []

    def visit(net: str) -> None:
        if state.get(net) == 1:
            return
        if state.get(net) == 0:
            cycle = stack[stack.index(net) :] + [net]
            raise GenError(
                f"module '{mod.name}': combinational loop through nets: {' -> '.join(cycle)}"
            )
        state[net] = 0
        stack.append(net)
        for src in driver[net].pin_to_net.values():
            if src not in inputs:
                visit(src)
        stack.pop()
        state[net] = 1
        order.append(net)

    for net in driver:
        visit(net)
    return order


def gold_sv_expr(gm: GoldModel, ga: GoldAssign) -> str:
    subst = {pin: gm.gold_name(net) for pin, net in ga.pin_to_net.items()}
    return render_sv(ga.ast, subst)


def gold_flat_expr(gm: GoldModel, net: str, cache: dict[str, str]) -> str:
    """Flatten a net's function all the way down to the module's primary inputs."""
    if net in cache:
        return cache[net]
    ga = next(a for a in gm.assigns if a.net == net)
    subst = {}
    for pin, src in ga.pin_to_net.items():
        subst[pin] = src if src in gm.module.inputs else gold_flat_expr(gm, src, cache)
    expr = render_sv(ga.ast, subst)
    cache[net] = expr
    return expr


def gold_truth_table(gm: GoldModel) -> dict[str, list[int]]:
    """Evaluate the gold model over every input vector; also proves it is resolvable."""
    mod = gm.module
    table: dict[str, list[int]] = {o: [] for o in mod.outputs}
    for vals in itertools.product((0, 1), repeat=len(mod.inputs)):
        env = dict(zip(mod.inputs, vals))
        for ga in gm.assigns:  # already topologically ordered
            local = {pin: env[net] for pin, net in ga.pin_to_net.items()}
            env[ga.net] = eval_node(ga.ast, local)
        for o in mod.outputs:
            table[o].append(env[o])
    return table


