#!/usr/bin/env python3
# SPDX-License-Identifier: Apache-2.0 WITH SHL-2.1
"""Generate exhaustive self-checking testbenches for a std-cell netlist.

Reads a structural Verilog netlist (e.g. ``aion_cells.v``, generated by ``aion_opt``)
whose modules are built purely from IHP ``sg13g2_*`` combinational standard cells, and
emits one SystemVerilog testbench per module that:

  * sweeps **every** input combination (modules here have <= 9 inputs),
  * compares the DUT outputs against a *gold* model built from the PDK Liberty
    ``function`` attributes -- an oracle independent of the Verilog being tested,
  * XORs the two and fails loudly (``$fatal``) on any mismatch.

The gold model is *structural*: one continuous assign per standard-cell instance, using
the cell's Liberty function with its formal pins substituted by the gold name of the
actual net.  Gold signals never read a DUT signal.

Note on ``sp2bool``: the lctime ``sp2bool`` tool shipped in the container cannot be used
as an oracle for this PDK.  ``lctime/lccommon/net_util.py::get_channel_type()`` classifies
a device as NMOS only when its model name *starts with* ``n``; the IHP models are
``sg13_lv_nmos``/``sg13_lv_pmos``, so every transistor is taken to be a PMOS and even
``sg13g2_inv_1`` comes out as ``Y = True``.  With the model names shimmed it still mis-solves
the deeper series stacks (``nand3_1``, ``nand4_1``, ``nor3_1``).  The Liberty functions were
cross-checked against a transistor-network solve of ``sg13g2_stdcell.cdl`` and agree for
every cell used here.

Every library path is an explicit argument, so the tool is not tied to any one PDK. For the
SG13G2 paths used by this repo, `macros/custom_std_cells/Makefile` fills them in:

    ./run.sh "make -C macros/custom_std_cells generate"

which expands to roughly:

    gen_cell_tb.py macros/custom_std_cells/aion_cells.v \\
        --lib $PDK_ROOT/$PDK/libs.ref/sg13g2_stdcell/lib/sg13g2_stdcell_typ_1p20V_25C.lib \\
        --cell-verilog $PDK_ROOT/$PDK/libs.ref/sg13g2_stdcell/verilog/sg13g2_stdcell.v \\
        --cell-verilog $PDK_ROOT/$PDK/libs.ref/sg13g2_stdcell/verilog/sg13g2_udp.v

Both must run inside the EDA container: the PDK lives at /foss/pdks, which the host cannot see.
"""

